"""Export an endpoint inventory without pretending OpenAPI describes object authorization."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
api = json.loads((root / 'contracts/generated/openapi.json').read_text())
features = json.loads((root / 'contracts/generated/features.json').read_text())
rows = []
for path, methods in api['paths'].items():
    for method, operation in methods.items():
        if method not in ('get', 'post', 'put', 'patch', 'delete', 'head', 'options'):
            continue
        public = operation.get('security', api.get('security')) == []
        rows.append((path, method.upper(), ', '.join(operation.get('tags', [])), 'Public' if public else 'Authenticated'))
output = root / 'docs/security/endpoint-inventory.md'
lines = ['# Endpoint security inventory', '',
         'Generated by `python infra/diagnostics/export-security-inventory.py` from the checked-in contracts.', '',
         '**This is an inventory, not per-route proof of role/object authorization.** OpenAPI does not encode account ownership, Team membership, field visibility, subscription state or background-worker policies. See the module matrix and evidence in the hardening report. `ApiBoundaryTests` discovers actual runtime routes and tests anonymous rejection, including routes absent from this contract.', '',
         f'{len(rows)} HTTP operations; {len(features)} registered capability definitions.', '',
         '| Method | Route | Tags | Authentication contract |', '| --- | --- | --- | --- |']
lines += [f'| {method} | `{path}` | {tags} | {auth} |' for path, method, tags, auth in sorted(rows)]
lines += ['', '## Capability inventory', '', '| Capability | Owning module |', '| --- | --- |']
lines += [f"| `{item['key']}` | {item['module']} |" for item in sorted(features, key=lambda item: item['key'])]
output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'Inventoried {len(rows)} operations and {len(features)} capabilities.')
